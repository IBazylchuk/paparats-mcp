#!/usr/bin/env bash
# Runs each time the container starts. Waits for the server, then writes
# projects.yml so the indexer picks up the repo via its hot-reload watcher.
#
# With the CPU embedding server only packages/shared/src is indexed: the whole
# repo would take 15+ minutes on a Codespace. With a cloud embedding key
# (VOYAGE_API_KEY or OPENAI_API_KEY as a Codespaces secret) the whole repo is
# indexed.
set -euo pipefail

SERVER_URL="${PAPARATS_SERVER_URL:-http://paparats:9876}"
PAPARATS_HOME="${HOME}/.paparats"

echo "== Waiting for paparats-mcp at ${SERVER_URL} =="
for i in $(seq 1 90); do
  if curl -fsS "${SERVER_URL}/health" >/dev/null 2>&1; then
    echo "  ready after ${i}s"
    break
  fi
  sleep 1
done

if ! curl -fsS "${SERVER_URL}/health" >/dev/null 2>&1; then
  echo "!! The server did not answer in 90s. Run 'paparats doctor' to see what is missing."
  exit 0
fi

if [ -n "${VOYAGE_API_KEY:-}" ] || [ -n "${OPENAI_API_KEY:-}" ]; then
  SCOPE="the whole repo"
  PATHS=""
else
  SCOPE="packages/shared/src"
  PATHS="    indexing:
      paths:
        - 'packages/shared/src/**'"
fi

mkdir -p "${PAPARATS_HOME}"
cat > "${PAPARATS_HOME}/projects.yml" <<YML
# Auto-generated by .devcontainer/post-start.sh for the Codespaces demo.
# Edit freely — the indexer hot-reloads on save.
repos:
  - path: /workspaces/paparats-mcp
    name: paparats-mcp
    group: demo
    language: typescript
${PATHS}
YML

echo
echo "== Registered paparats-mcp (group=demo, scope: ${SCOPE}) =="
echo "The first index takes a few minutes on the CPU embedding server."
echo "Watch progress: paparats list"
echo "Then try:       paparats search -g demo 'gitignore filter'"
